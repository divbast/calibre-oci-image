// Package pins generates the image's Python locks from what the repository
// pins: the requirements python/requirements.in gives, the DHI Python
// image in the Containerfile, and python/pins.txt.
//
// The requirements are the app's own list, in requirements.in, or its
// upstream's, which requirements.in names by -r lines, one for each file,
// at the commit the Containerfile builds. Either way they are "upstream"
// here: what pins.txt may add to, and never override.
//
// It also fills the Containerfile's empty checksums, and writes the tag
// IMAGE_PAIR.
package pins

import (
	"bufio"
	"bytes"
	"context"
	"errors"
	"fmt"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strings"
	"sync"
	"time"
)

// The files Generate reads and writes, by their paths in the repository.
const (
	ContainerfilePath    = "Containerfile"
	RequirementsPath     = "python/requirements.in"
	PinsPath             = "python/pins.txt"
	RequirementsLockPath = "python/requirements.lock"
	BuildLockPath        = "python/build.lock"
	FilesPath            = "python/files.txt"
)

// Sources are where Generate reads upstream from.
type Sources struct {
	PyPI *PyPI
	// Client fetches the file a -r line in requirements.in names.
	Client *http.Client
	// Delays are the waits between tries: DefaultDelays when nil.
	Delays []time.Duration
}

// DefaultSources are the public servers.
func DefaultSources() Sources {
	c := &http.Client{}
	return Sources{PyPI: &PyPI{Base: "https://pypi.org", Client: c}, Client: c}
}

// fetchers bounds how many PyPI requests Generate makes at once.
const fetchers = 8

// Generate reads the Containerfile, requirements.in and pins.txt in root,
// and returns the contents those pins give the locks, by path:
//   - requirements.lock, from the requirements, for Linux and the
//     Containerfile's Python, merged with the pins they leave to pins.txt;
//   - build.lock, pins.txt's build backends;
//   - files.txt, every file of both locks by its sha256 and its URL;
//   - renovate-bounds.json, a Renovate preset with a rule for each pin
//     that upstream or a package of either lock bounds, as Bounds says,
//     so Renovate proposes no version of it the build would refuse;
//   - the Containerfile, with each empty checksum of Fills set to the sha256
//     of the file its URL serves now, as FillHashes says, and IMAGE_PAIR
//     set from CALIBRE_VERSION and CALIBRE_WEB_COMMIT.
//
// The notes are what a person should know though nothing failed: each
// checksum filled in, and each yanked release the requirements pin with ==,
// which the lock keeps.
//
// The same pins and the same upstream give the same bytes.
func Generate(ctx context.Context, src Sources, root *os.Root) (out map[string][]byte, notes []string, err error) {
	cf, err := root.ReadFile(ContainerfilePath)
	if err != nil {
		return nil, nil, err
	}
	args, err := ReadArgs(cf)
	if err != nil {
		return nil, nil, err
	}
	pinsTxt, err := root.ReadFile(PinsPath)
	if err != nil {
		return nil, nil, err
	}
	pins, err := ParsePins(bytes.NewReader(pinsTxt))
	if err != nil {
		return nil, nil, err
	}
	reqs, from, err := requirements(ctx, src, root, cf, MarkerEnv{PythonVersion: args.PythonVersion, SysPlatform: "linux", PlatformSystem: "Linux"})
	if err != nil {
		return nil, nil, err
	}
	again := "Do not edit it: change the pins, then run go run ./cmd/divbast-pins again."
	header := make([]string, 0, 3+len(from))
	if from == nil {
		header = append(header, "Generated by go run ./cmd/divbast-pins from "+RequirementsPath)
	} else {
		header = append(header, "Generated by go run ./cmd/divbast-pins from the requirements "+RequirementsPath+" names,")
		header = append(header, from...)
	}
	header = append(header, "and python/pins.txt, for Linux and Python "+args.PythonVersion+".", again)
	runtime, err := Merge(reqs, pins)
	if err != nil {
		return nil, nil, err
	}
	pypi := *src.PyPI
	pypi.Delays = src.Delays
	locked, err := choose(ctx, &pypi, runtime, ChooseFiles)
	if err != nil {
		return nil, nil, err
	}
	backends, err := choose(ctx, &pypi, Build(pins), ChooseBuildFiles)
	if err != nil {
		return nil, nil, err
	}
	bounds, err := Bounds(pins, reqs, locked, backends, DistEnvs(args.PythonFullVersion))
	if err != nil {
		return nil, nil, err
	}

	newCF, fillNotes, err := FillHashes(ctx, src.Client, cf, Fills)
	if err != nil {
		return nil, nil, err
	}
	notes = fillNotes
	pair, err := imagePair(newCF)
	if err != nil {
		return nil, nil, err
	}
	if newCF, err = SetArg(newCF, "IMAGE_PAIR", pair); err != nil {
		return nil, nil, err
	}

	var req, build, list, limits bytes.Buffer
	err = errors.Join(
		WriteLock(&req, Lock{Header: header, Packages: locked}),
		WriteLock(&build, Lock{Header: []string{
			"Generated by go run ./cmd/divbast-pins from python/pins.txt: the build backends",
			"the source builds need, which never ship in the image.",
			again,
		}, Packages: backends}),
		WriteFiles(&list, []string{
			"Generated by go run ./cmd/divbast-pins: every file requirements.lock and build.lock",
			"let pip install, by its sha256 and the URL PyPI serves it at. The build fetches each",
			"and checks it before pip reads anything, so no package's code runs with the network on.",
			again,
		}, slices.Concat(locked, backends)),
		WriteBounds(&limits, bounds),
	)
	if err != nil {
		return nil, nil, err
	}
	for _, l := range locked {
		if l.Yanked {
			reason := "with no reason given"
			if l.YankedReason != "" {
				reason = "for " + l.YankedReason
			}
			notes = append(notes, fmt.Sprintf("%s %s, which the requirements pin with ==, is yanked on PyPI, %s: "+
				"kept, as pip installs a yanked release pinned with ==", l.Name, l.Version, reason))
		}
	}
	return map[string][]byte{
		ContainerfilePath: newCF, RequirementsLockPath: req.Bytes(), BuildLockPath: build.Bytes(), FilesPath: list.Bytes(),
		BoundsPath: limits.Bytes(),
	}, notes, nil
}

// include is a -r line, which names another requirements file.
var include = regexp.MustCompile(`^(?:-r|--requirement)(?:\s+|=)(\S+)$`)

// pinnedByCommit is a full commit SHA, as a path segment of a URL.
var pinnedByCommit = regexp.MustCompile(`/[0-9a-f]{40}/`)

// requirements returns the requirements requirements.in gives, and where
// they are from, for the lock's header: nil for requirements.in's own, or
// the URL of each file its -r lines name, in order. Each is an https URL
// whose ${NAME}s are the Containerfile cf's ARGs, and all name one full
// commit, so the same Containerfile always locks the same requirements. The
// files' requirements are in file order. A package in two files at one
// specifier is kept once, and at two is an error. A requirements.in with
// both its own requirements and -r lines is an error.
func requirements(ctx context.Context, src Sources, root *os.Root, cf []byte, env MarkerEnv) (reqs []Requirement, from []string, err error) {
	in, err := root.ReadFile(RequirementsPath)
	if err != nil {
		return nil, nil, err
	}
	var urls []string
	listed := false
	sc := bufio.NewScanner(bytes.NewReader(in))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		line = strings.TrimSpace(line)
		if m := include.FindStringSubmatch(line); m != nil {
			urls = append(urls, m[1])
		} else if line != "" {
			listed = true
		}
	}
	if scanErr := sc.Err(); scanErr != nil {
		return nil, nil, scanErr
	}
	if len(urls) == 0 {
		reqs, err = ParseRequirements(bytes.NewReader(in), env)
		if err != nil {
			err = fmt.Errorf("%s: %w", RequirementsPath, err)
		}
		return reqs, nil, err
	}
	if listed {
		return nil, nil, fmt.Errorf("%s holds requirements or -r lines naming an upstream's, not both", RequirementsPath)
	}
	commit := ""
	for _, u := range urls {
		url, err := Expand(cf, u)
		if err != nil {
			return nil, nil, fmt.Errorf("%s's -r line: %w", RequirementsPath, err)
		}
		c := pinnedByCommit.FindString(url)
		switch {
		case !strings.HasPrefix(url, "https://"):
			return nil, nil, fmt.Errorf("%s's -r line names %s, which is not https", RequirementsPath, url)
		case c == "":
			return nil, nil, fmt.Errorf("%s's -r line names %s, at no full commit: name one by the Containerfile's ARG, as ${APP_COMMIT}", RequirementsPath, url)
		case commit != "" && c != commit:
			return nil, nil, fmt.Errorf("%s's -r line names %s, at commit %s, but another names %s: every file must be at one commit",
				RequirementsPath, url, strings.Trim(c, "/"), strings.Trim(commit, "/"))
		}
		commit = c
		from = append(from, url)
	}
	at := map[string]string{} // package, by its normalised name, to the URL that first asked for it
	var merged []Requirement
	for _, url := range from {
		text, err := get(ctx, src.Client, url, src.Delays)
		if err != nil {
			return nil, nil, err
		}
		got, err := ParseRequirements(bytes.NewReader(text), env)
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", url, err)
		}
		for _, r := range got {
			key := Normalize(r.Name)
			i := slices.IndexFunc(merged, func(m Requirement) bool { return Normalize(m.Name) == key })
			switch {
			case i < 0:
				merged = append(merged, r)
				at[key] = url
			case merged[i].Specifier == r.Specifier:
			case merged[i].Specifier == "" && isPin(r):
				merged[i], at[key] = r, url
			case isPin(merged[i]) && r.Specifier == "":
			default:
				return nil, nil, fmt.Errorf("%s is asked for at %q by %s and at %q by %s; this tool reads one of each package",
					r.Name, merged[i].Specifier, at[key], r.Specifier, url)
			}
		}
	}
	return merged, from, nil
}

// isPin is whether r pins its package with ==.
func isPin(r Requirement) bool {
	_, ok := r.Pinned()
	return ok
}

// choose runs pick on each of pinned, a few at once, and returns the
// results in pinned's order, or every error, joined.
func choose(ctx context.Context, c *PyPI, pinned []Pinned, pick func(context.Context, *PyPI, Pinned) (Locked, error)) ([]Locked, error) {
	out := make([]Locked, len(pinned))
	errs := make([]error, len(pinned))
	slots := make(chan struct{}, fetchers)
	var wg sync.WaitGroup
	for i, p := range pinned {
		wg.Go(func() {
			slots <- struct{}{}
			defer func() { <-slots }()
			out[i], errs[i] = pick(ctx, c, p)
		})
	}
	wg.Wait()
	return out, errors.Join(errs...)
}
